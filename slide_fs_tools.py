def build_smoothness_matrices(pm_top, pm_top_seg_id, pm, nve):
    # smoothing matrix
    # remove nve as argument and manually load that from cfg file

    list_id = np.unique(pm_top_seg_id)
    N = pm_top.shape[0]
    total_patches = N + pm.shape[0]

    # first double check the dimensions are the same...
    if total_patches != nve * N:
        raise (
            ValueError(
                "Incorrect dimensions. len(pm_top)*nve should equal total number of patches"
            )
        )

    pm_smooth_hz = np.zeros((total_patches, total_patches))
    pm_smooth_vert = np.zeros((total_patches, total_patches))

    for segment_id in list_id:
        # Get indices of patches belonging to the current segment
        patch_indices = np.where(pm_top_seg_id == segment_id)[0]

        for j, patch_idx in enumerate(patch_indices):
            # Horizontal smoothness for the top row
            if j < len(patch_indices) - 1:  # Ensure we don't exceed the array length
                pm_smooth_hz[patch_idx, patch_idx] = 1
                pm_smooth_hz[patch_idx, patch_indices[j + 1]] = (
                    -1
                )  # Smooth patch to the left

            # Vertical smoothness for the top row
            pm_smooth_vert[patch_idx, patch_idx] = 1
            pm_smooth_vert[patch_idx, N + (nve - 1) * patch_idx] = (
                -1
            )  # Smooth patch below

            # Additional rows for vertical elements
            for m in range(nve - 2):  # Loop over additional vertical elements
                base_idx = N + (nve - 1) * patch_idx + m
                pm_smooth_vert[base_idx, base_idx] = 1
                pm_smooth_vert[base_idx, base_idx + 1] = (
                    -1
                )  # Smooth patch to the next vertical element

                if j < len(patch_indices) - 1:
                    pm_smooth_hz[base_idx, base_idx] = 1
                    pm_smooth_hz[base_idx, base_idx + (nve - 1)] = (
                        -1
                    )  # Smooth to the left

    # Combine horizontal and vertical smoothness matrices after removing zero rows
    pm_smooth_hz = pm_smooth_hz[np.any(pm_smooth_hz != 0, axis=1)]
    pm_smooth_vert = pm_smooth_vert[np.any(pm_smooth_vert != 0, axis=1)]
    pm_smooth = np.vstack((pm_smooth_hz, pm_smooth_vert))

    return pm_smooth


class build_GFs:
    def __init__(
        self,
        FaultInfo,
        mesh,
        obs_xyz,
        dlock_max,
        pL,
        total_nve,
        variable_rake,
        include_moment,
        calc_visco,
        tri_mom,
        use_gaussian_prior,
        nu,
    ):
        self.mesh = mesh
        self.obs_xyz = obs_xyz
        self.variable_rake = variable_rake
        self.include_moment = include_moment
        self.tri_mom = tri_mom
        self.calc_visco = calc_visco
        self.nu = nu
        self.faults_top = []
        self.faults_bot = []

        self.G_top = {key: [] for key in ["Exx", "Exy", "Eyy"]}
        self.G_bot = {key: [] for key in ["Exx", "Exy", "Eyy"]}

        if self.calc_visco:
            self.G_top_cycle = {key: [] for key in ["Exx", "Exy", "Eyy"]}
            self.G_bot_cycle = {key: [] for key in ["Exx", "Exy", "Eyy"]}

        if variable_rake:

            self.G_top_perp = {key: [] for key in ["Exx", "Exy", "Eyy"]}
            self.G_bot_perp = {key: [] for key in ["Exx", "Exy", "Eyy"]}

            if self.calc_visco:
                self.G_top_cycle_perp = {key: [] for key in ["Exx", "Exy", "Eyy"]}
                self.G_bot_cycle_perp = {key: [] for key in ["Exx", "Exy", "Eyy"]}

        self.FaultInfo = FaultInfo
        self.dlock_max = dlock_max
        self.pL = pL
        self.total_nve = total_nve

        self.use_gaussian_prior = use_gaussian_prior

    def make_fault_lists(self, top=True):

        fault_list = self.faults_top if top else self.faults_bot

        # how deep should pm extend? if top, divide by total_nve, else use dlock_max
        fault_depth = self.dlock_max / self.total_nve if top else self.dlock_max

        # subdivide into 1 km patches for top, don't subdivide (using arbitrarily high refine_length) for bottom
        refine_length = 1 if top else 1e6

        nve = 1 if top else self.total_nve

        for matlab_fault in self.FaultInfo:

            fault = make_fault_from_matlab(matlab_fault, fault_depth)
            segends = normalize_fault_segs(matlab_fault["SegEnds"].item(), self.pL)

            # manual shift around singularity...
            if fault.fault_name == "Calaveras (south)" and top:
                segends[2] += 0.01

            for segment in segends:
                patch = fault.add_segment(segment)

                patch.refine_patches(nve=nve, refine_length=refine_length)

                # for lower patches, remove top layer
                if not top:
                    patch.fine_patches = patch.fine_patches[patch.nhe :]
                    patch.nve -= patch.nhe

            fault_list.append(fault)

    def get_top_gfs(self, perp=False):
        fault_list = self.faults_top
        G = self.G_top_perp if perp else self.G_top
        G_cycle = (
            self.G_top_cycle_perp
            if (self.calc_visco and perp)
            else self.G_top_cycle if self.calc_visco else None
        )

        for fault in fault_list:
            for patch in fault.segments:

                slip = patch.get_slip(perp)

                patch.compute_disloc(slip, self.mesh["tri_centroids"])
                patch.get_strain()

                if self.calc_visco:

                    E_visc = patch.compute_visco_strain(slip, self.obs_xyz)

                    for key, value in zip(G_cycle, E_visc):
                        G_cycle[key].append(value)

            # Builds GExx, GEyy, GExy for each fault
            fault.compute_green_functions(piecewise=True)

            # append these to G_top_fine
            for key, value in zip(G, [fault.GExx, fault.GExy, fault.GEyy]):
                G[key].append(value)

        for key in G:
            G[key] = interpolate_all(
                self.mesh["tri_centroids"], (np.concatenate(G[key], axis=1)), self.obs_xyz
            )
            if self.calc_visco:
                G_cycle[key] = np.array(G_cycle[key]).T

    def get_bot_gfs(self, perp=False):

        fault_list = self.faults_bot

        G = self.G_bot_perp if perp else self.G_bot
        G_cycle = (
            self.G_bot_cycle_perp
            if (self.calc_visco and perp)
            else self.G_bot_cycle if self.calc_visco else None
        )

        for fault in fault_list:
            for patch in fault.segments:

                slip = patch.get_slip(perp)

                patch.compute_disloc(slip, self.mesh["tri_centroids"])
                patch.get_strain()

                for key, value in zip(G, [patch.Exx, patch.Exy, patch.Eyy]):
                    G[key].append(value.sum(axis=1))

                # insteads of just calling for each patch, loop through vertical elements and run viscoelastic GFs on all elements
                if self.calc_visco:
                    for i in range(patch.nve):
                        pm_vert = patch.fine_patches[i * patch.nhe]

                        E_visc = patch.compute_visco_strain(slip, self.obs_xyz, pm=pm_vert)

                        for key, value in zip(G_cycle, E_visc):
                            G_cycle[key].append(value)

        for key in G:
            G[key] = interpolate_all(
                self.mesh["tri_centroids"], (np.concatenate(G[key]).T), self.obs_xyz
            )

            if self.calc_visco:
                G_cycle[key] = np.array(G_cycle[key]).T

    def get_smoothing(self):
        # unwrap patch models to arrays

        pm_top = np.array([s.pm for f in self.faults_top for s in f.segments])
        pm = np.array(
            [p for f in self.faults_bot for s in f.segments for p in s.fine_patches]
        )

        self.num_slip = len(pm_top) + len(pm)

        pm_top_seg_id = np.array(
            [f.fault_id for f in self.faults_top for s in f.segments]
        )

        # create smoothness matrix
        self.pm_smooth = build_smoothness_matrices(
            pm_top, pm_top_seg_id, pm, self.total_nve
        )
        self.pm = pm
        self.pm_top = pm_top

    def process_moment_source(self):
        if not self.include_moment:
            return None

        if self.tri_mom:
            print(
                "Performing triangular moment source calculations. This is time intensive."
            )
            G_mom = force_couple.buildG_MomentSource_2d_tri(
                self.mesh, self.obs_xyz, self.nu
            )
        else:
            G_mom = force_couple.buildG_MomentSource_2d(
                self.mesh, self.obs_xyz, self.nu
            )
        G_mom_reshaped = []
        for E_component in G_mom.values():
            G_mom_reshaped.extend(
                np.hstack([values for values in E_component.values()])
            )
        self.G_mom = np.array(G_mom_reshaped) * 1e-3
        self.num_mom = self.G_mom.shape[1]

    def compute_all(self):
        self.make_fault_lists(top=True)

        self.make_fault_lists(top=False)
        self.get_smoothing()

        print("Calculating shallow patch Green's Functions")
        self.get_top_gfs(perp=False)
        print("Calculating deep patch Green's Functions")
        self.get_bot_gfs(perp=False)

        if self.variable_rake:

            print("Calculating perpendicular rake shallow patch Green's Functions")
            self.get_top_gfs(perp=True)
            print("Calculating perpendicular rake deep patch Green's Functions")
            self.get_bot_gfs(perp=True)

        if self.include_moment:
            print("Calculating moment source Green's Functions")
            self.process_moment_source()

        else:
            self.G_mom = None

    def return_greens(self):
        return {
            "G_top": self.G_top,
            "G_top_cycle": self.G_top_cycle if self.calc_visco else None,
            "G_bot": self.G_bot,
            "G_bot_cycle": self.G_bot_cycle if self.calc_visco else None,
            "G_top_perp": self.G_top_perp if self.variable_rake else None,
            "G_top_cycle_perp": (
                self.G_top_cycle_perp
                if (self.variable_rake and self.calc_visco)
                else None
            ),
            "G_bot_perp": self.G_bot_perp if self.variable_rake else None,
            "G_bot_cycle_perp": (
                self.G_bot_cycle_perp
                if (self.variable_rake and self.calc_visco)
                else None
            ),
            "G_mom": self.G_mom if self.include_moment else None,
        }


class Inversion:
    def __init__(self, GF_obj, d, Esig):

        self.G_top = getattr(GF_obj, "G_top", None)
        self.G_bot = getattr(GF_obj, "G_bot", None)

        self.G_top_perp = getattr(GF_obj, "G_top_perp", None)
        self.G_bot_perp = getattr(GF_obj, "G_bot_perp", None)

        self.G_top_cycle = getattr(GF_obj, "G_top_cycle", None)
        self.G_bot_cycle = getattr(GF_obj, "G_bot_cycle", None)

        self.G_top_cycle_perp = getattr(GF_obj, "G_top_cycle_perp", None)
        self.G_bot_cycle_perp = getattr(GF_obj, "G_bot_cycle_perp", None)

        self.G_mom = getattr(GF_obj, "G_mom", None)
        self.num_mom = getattr(GF_obj, "num_mom", 0)
        self.num_slip = getattr(GF_obj, "num_slip", 0)

        self.obs_xyz = GF_obj.obs_xyz
        self.num_slip = GF_obj.num_slip
        self.mesh = GF_obj.mesh
        self.nu = GF_obj.nu
        self.pm_smooth = GF_obj.pm_smooth
        self.Esig = Esig
        self.d = d

        self.faults_top = GF_obj.faults_top
        self.faults_bot = GF_obj.faults_bot

        self.pm_top = GF_obj.pm_top
        self.pm = GF_obj.pm

        self.calc_visco = GF_obj.calc_visco
        self.variable_rake = GF_obj.variable_rake
        self.include_moment = GF_obj.include_moment
        self.tri_mom = getattr(GF_obj, "tri_mom")
        self.use_gaussian_prior = getattr(GF_obj,"use_gaussian_prior", False)

        # run some basic input checks
        if not self.G_top and not self.G_bot:
            raise ValueError("No GFs found. Please run build_GFs first.")

        if not (self.G_top_perp or self.G_bot_perp) and self.variable_rake:
            raise ValueError("No perpendicular GFs found. Check variable_rake flag.")

        if not (self.G_top_cycle or self.G_bot_cycle) and self.calc_visco:
            raise ValueError("No viscoelastic GFs found. Check calc_visco flag.")

        if not (self.G_top_cycle_perp or self.G_bot_cycle_perp) and (self.calc_visco and self.variable_rake):
            raise ValueError("No perpendicular viscoelastic GFs found. Check variable_rake and calc_visco flags.")

        self.G = None
        self.ub = None
        self.lb = None
        self.GG = None
        self.dd = None

    def build_G(self):

        G_upper = {"Exx": [], "Exy": [], "Eyy": []}
        G_main = {"Exx": [], "Exy": [], "Eyy": []}

        if self.variable_rake:
            G_upper_perp = {"Exx": [], "Exy": [], "Eyy": []}
            G_main_perp = {"Exx": [], "Exy": [], "Eyy": []}

        for key in G_main:

            # make negative because we're solving for backslip
            # if self.use_elastic:
            G_upper[key] = -self.G_top[key]
            G_main[key] = -self.G_bot[key]

            if self.variable_rake:
                G_upper_perp[key] = -self.G_top_perp[key]
                G_main_perp[key] = -self.G_bot_perp[key]

            if self.calc_visco:
                G_upper[key] += 1000 * self.G_top_cycle[key] * 1e-6
                G_main[key] += 1000 * self.G_bot_cycle[key] * 1e-6

                if self.variable_rake:
                    G_upper_perp[key] += 1000 * self.G_top_cycle_perp[key] * 1e-6
                    G_main_perp[key] += 1000 * self.G_bot_cycle_perp[key] * 1e-6
        G = []
        for key in G_main:
            G.extend(np.hstack((G_upper[key], G_main[key])))

        self.G = np.array(G)
        if self.variable_rake:
            G_perp = []
            for key in G_main_perp:
                G_perp.extend(np.hstack((G_upper_perp[key], G_main_perp[key])))
            self.G_perp = np.array(G_perp)
            self.G = np.hstack((self.G, G_perp))

        if self.include_moment:

            self.G = np.hstack((self.G, self.G_mom))

    def set_bounds(
        self,
        use_upper_bounds=True,
        use_lower_bounds=False,
        scale_upper_bounds=10,
        scale_lower_bounds=1,
    ):
        upper_bound_top = np.array(
            [
                fault.ub_slip
                for fault in self.faults_top
                for segment in fault.segments
                for _ in range(segment.nve)
            ]
        )
        upper_bound = np.array(
            [
                fault.ub_slip
                for fault in self.faults_bot
                for segment in fault.segments
                for _ in range(segment.nve)
            ]
        )
        lower_bound_top = np.array(
            [
                fault.lb_slip
                for fault in self.faults_top
                for segment in fault.segments
                for _ in range(segment.nve)
            ]
        )
        lower_bound = np.array(
            [
                fault.lb_slip
                for fault in self.faults_bot
                for segment in fault.segments
                for _ in range(segment.nve)
            ]
        )

        if use_upper_bounds:
            ub = np.hstack((upper_bound_top, upper_bound)) / 1000  # Convert to meters
            if self.variable_rake:
                ub = np.tile(ub, 2)
            if self.include_moment:
                mom_ub = np.full(self.G.shape[1] - len(ub), np.inf)
                ub = np.hstack((ub, mom_ub))
        else:
            ub = np.full(self.G.shape[1], np.inf)

        if use_lower_bounds:
            lb = np.hstack((lower_bound_top, lower_bound)) / 1000
            if self.variable_rake:
                lb = np.tile(lb, 2)
            if self.include_moment:
                mom_lb = np.full(self.G.shape[1] - len(lb), -np.inf)
                lb = np.hstack((lb, mom_lb))
        else:
            lb = np.zeros(lower_bound.shape[0] + lower_bound_top.shape[0])
            if self.variable_rake:
                lb_rake = -np.hstack((upper_bound_top, upper_bound)) / 1000
                lb = np.hstack((lb, lb_rake))
            if self.include_moment:
                mom_lb = np.full(self.G.shape[1] - len(lb), -np.inf)
                lb = np.hstack((lb,  mom_lb))

        self.ub = ub * scale_upper_bounds
        self.lb = lb * scale_lower_bounds

    def get_priors(self, use_bounds_for_std = True):
        std_scale = 0.1
        mean_s_prior = np.array([f.slip for f in self.faults_top for p in f.segments])
        mean_s_prior = 1e-3 * np.hstack((mean_s_prior, np.array([f.slip for f in self.faults_bot for p in f.segments for pf in p.fine_patches])))
        if use_bounds_for_std:
            std_s_prior = np.array([f.ub_slip - f.lb_slip for f in self.faults_top for p in f.segments])
            std_s_prior = std_scale * 1e-3 * np.hstack((std_s_prior, np.array([f.ub_slip-f.lb_slip for f in self.faults_bot for p in f.segments for pf in p.fine_patches])))

            if np.any(std_s_prior <= 0):
                print("Warning: for some faults, upper and lower bounds are equal. Setting their std dev to 10 mm/yr")
                std_s_prior[std_s_prior<=0] = 10/1000
            else:
                std_s_prior = np.array([f.std_slip for f in self.faults_top for p in f.segments])
                std_s_prior = 1e-3 * np.hstack((std_s_prior, np.array([f.std_slip for f in self.faults_bot for p in f.segments for pf in p.fine_patches])))

        self.mean_s_prior = mean_s_prior
        self.std_s_prior = std_s_prior

    def normalize_and_weight(self, weight_smooth = 1e3, weight_rake = 1e3, weight_moment = 1e3):

        W = self.pm_smooth * weight_smooth

        if self.variable_rake:
            W = np.tile(W, 2)
        if self.include_moment:
            W = np.hstack((W, np.zeros((self.pm_smooth.shape[0], self.num_mom))))
        self.W = W

        if self.use_gaussian_prior:
            self.get_priors()
            # Construct Gprior for variable rake
            Gprior = np.diag(1.0 / self.std_s_prior)
            # stack zeros for variable rake Prior...
            Gprior = np.hstack((Gprior, np.zeros_like(Gprior))) if self.variable_rake else Gprior
            Gprior = np.hstack((Gprior, np.zeros((self.num_slip, self.num_mom)))) if self.include_moment else Gprior
            # Construct dd and GG
            self.GG = np.vstack((self.G / np.tile(self.Esig.reshape(-1, 1), self.G.shape[1]), Gprior, W))
            dd = np.concatenate((self.d / self.Esig, self.mean_s_prior / self.std_s_prior, np.zeros(self.pm_smooth.shape[0])))
            self.Gprior = Gprior
        else:
            # Construct dd and GG without Gaussian prior
            self.GG = np.vstack((self.G / np.tile(self.Esig.reshape(-1, 1), self.G.shape[1]), W))
            dd = np.concatenate((self.d / self.Esig, np.zeros((self.pm_smooth.shape[0]))))

        # if using variable rake, add in perpendicular damping terms
        if self.variable_rake:
            eye_slip = np.eye(self.num_slip)
            Gdamp_perp = np.hstack((np.zeros_like(eye_slip), weight_rake * eye_slip))

            if self.include_moment:
                Gdamp_perp = np.hstack(
                    (Gdamp_perp, np.zeros((self.num_slip, self.num_mom)))
                )
            self.Gdamp_perp = Gdamp_perp
            self.GG = np.vstack((self.GG, Gdamp_perp))
            dd = np.hstack((dd, np.zeros(self.num_slip)))

        # if using moment, add in moment damping terms
        if self.include_moment:

            Gdamp_mom = np.zeros((self.num_mom, self.num_slip))

            if self.variable_rake:
                Gdamp_mom = np.tile(Gdamp_mom, 2)

            self.Gdamp_mom = np.hstack((Gdamp_mom, weight_moment * np.eye(self.num_mom)))

            self.GG = np.vstack((self.GG, self.Gdamp_mom))
            dd = np.hstack((dd, np.zeros(self.num_mom)))

        # self.GG = GG
        self.dd = dd

    def run_inversion(self, verbose=False):
        # sparse solution doesn't substantially speed up the problem
        # could be removed to save a trivial amount of time for smaller
        # problems or included to save time on larger problems

        # Convert GG to a sparse matrix
        GG_sparse = csr_matrix(self.GG)

        # Define the optimization variables
        mhat = cp.Variable(GG_sparse.shape[1])

        # Define the objective function
        objective = cp.Minimize(cp.sum_squares(GG_sparse @ mhat - self.dd))

        # Define the bounds
        constraints = [mhat >= self.lb, mhat <= self.ub]

        # Solve the problem
        problem = cp.Problem(objective, constraints)
        problem.solve(
            solver=cp.OSQP, verbose=verbose
        )  # solver=cp.CLARABEL (default) works as well. OSQP seems to be faster for this problem

        # Get the solution
        self.mhat = mhat.value

        slip_idx = self.num_slip * (self.variable_rake + 1)

        self.mhat_bs = self.mhat[:slip_idx]
        if self.include_moment:
            self.mhat_mom = self.mhat[slip_idx:]

        self.dhat = self.G @ self.mhat
        self.chi2 = (
            (self.d / self.Esig - self.dhat / self.Esig)
            @ (self.d / self.Esig - self.dhat / self.Esig)
            / len(self.d)
        )
        self.dhat = self.dhat
        self.data_Var = self.d @ self.d
        self.resid_Var = (self.d - self.dhat) @ (self.d - self.dhat)
        self.var_red = 1 - self.resid_Var / self.data_Var

        print(f"Chi-2: {self.chi2:.2f}")

    def post_process(self):

        ndat = len(self.d)//3
        Exx_mean = self.d[:ndat]
        Exy_mean = self.d[ndat:2*ndat]
        Eyy_mean = self.d[2*ndat:]

        pm_top = np.array([s.pm for f in self.faults_top for s in f.segments])
        pm = np.array(
            [p for f in self.faults_bot for s in f.segments for p in s.fine_patches]
        )
        area_top = np.prod(pm_top[:, :2], axis=1) * 1e6
        area_bot = np.prod(pm[:, :2], axis=1) * 1e6

        rake_top_patches = np.array(
            [s.rake for f in self.faults_top for s in f.segments]
        )
        rake_patches = np.array(
            [
                s.rake
                for f in self.faults_bot
                for s in f.segments
                for pf in s.fine_patches
            ]
        )

        NN = len(self.dhat) // 3
        Exx_tot = self.dhat[:NN]
        Exy_tot = self.dhat[NN : 2 * NN]
        Eyy_tot = self.dhat[2 * NN :]

        slip_idx = self.num_slip * (self.variable_rake + 1)

        dhat_bs = self.G[:, :slip_idx] @ self.mhat_bs
        Exx_bs = dhat_bs[:NN]
        Exy_bs = dhat_bs[NN : 2 * NN]
        Eyy_bs = dhat_bs[2 * NN :]

        if self.include_moment:
            dhat_mom = self.G[:, slip_idx:] @ self.mhat_mom
            Exx_bf = dhat_mom[:NN]
            Exy_bf = dhat_mom[NN : 2 * NN]
            Eyy_bf = dhat_mom[2 * NN :]

        max_shear = np.sqrt((Exx_mean - Eyy_mean) ** 2 + Exy_mean**2) * 1e6
        max_shear_bs = np.sqrt((Exx_bs - Eyy_bs) ** 2 + Exy_bs**2) * 1e6
        max_shear_bf = (
            np.sqrt((Exx_bf - Eyy_bf) ** 2 + Exy_bf**2) * 1e6
            if self.include_moment
            else np.zeros_like(max_shear_bs)
        )
        max_shear_tot = np.sqrt((Exx_tot - Eyy_tot) ** 2 + Exy_tot**2) * 1e6

        dilatation = 1e6 * (Exx_mean + Eyy_mean)
        dilatation_bs = 1e6 * (Exx_bs + Eyy_bs)
        dilatation_bf = 1e6 * (Exx_bf + Eyy_bf) if self.include_moment else 0
        dilatation_tot = 1e6 * (Exx_tot + Eyy_tot)

        max_shear_resid = 1e6 * np.sqrt(
            ((Exx_mean - Exx_tot) - (Eyy_mean - Eyy_tot)) ** 2
            + (Exy_mean - Exy_tot) ** 2
        )

        dilatation_resid = 1e6 * (Exx_mean - Exx_tot) + (Eyy_mean - Eyy_tot)

        if self.variable_rake:
            mhat_rake = self.mhat_bs[: self.num_slip]
            mhat_perp = self.mhat_bs[self.num_slip :]
        else:
            mhat_rake = self.mhat_bs

        top_idx = len(area_top)

        bs_top_rake = mhat_rake[:top_idx]
        bs_bot_rake = mhat_rake[top_idx:]

        if self.variable_rake:
            bs_top_perp = mhat_perp[:top_idx]
            bs_bot_perp = mhat_perp[top_idx:]

            bs_top = np.sqrt(bs_top_rake**2 + bs_top_perp**2)
            bs_bot = np.sqrt(bs_bot_rake**2 + bs_bot_perp**2)

        else:
            bs_top = bs_top_rake
            bs_bot = bs_bot_rake

        # compute rake
        if self.variable_rake:
            # Top vectors
            v_r_top_x = bs_top_rake * np.cos(np.radians(rake_top_patches))
            v_r_top_y = bs_top_rake * np.sin(np.radians(rake_top_patches))
            v_p_top_x = bs_top_perp * np.cos(np.radians(rake_top_patches + 90))
            v_p_top_y = bs_top_perp * np.sin(np.radians(rake_top_patches + 90))
            v_tot_top_x = v_r_top_x + v_p_top_x
            v_tot_top_y = v_r_top_y + v_p_top_y
            rake_top = np.degrees(np.arctan2(v_tot_top_y, v_tot_top_x))

            # Bottom vectors
            v_r_bot_x = bs_bot_rake * np.cos(np.radians(rake_patches))
            v_r_bot_y = bs_bot_rake * np.sin(np.radians(rake_patches))
            v_p_bot_x = bs_bot_perp * np.cos(np.radians(rake_patches + 90))
            v_p_bot_y = bs_bot_perp * np.sin(np.radians(rake_patches + 90))
            v_tot_bot_x = v_r_bot_x + v_p_bot_x
            v_tot_bot_y = v_r_bot_y + v_p_bot_y
            rake_bot = np.degrees(np.arctan2(v_tot_bot_y, v_tot_bot_x))
        else:
            rake_top = rake_top_patches
            rake_bot = rake_patches

        # On-fault moment calculation
        mu = 30e9  # shear modulus in N/m^2
        # Note: bs is in m/yr, Areas in m^2, so Mo is in N*m/yr
        self.Mo_fault = mu * np.sum(area_top * bs_top) + mu * np.sum(area_bot * bs_bot)

        # Off-fault moment calculation
        # Here we want to convert the weights (mhat_mom) on the moment sources to units of
        # Moment [Force*distance, N*m]. The moment GFs are unitless.  The weights are moment normalized by plate
        # thickness, H, Area of the triangle, and elastic shear modulus, mu
        # Need to multipiply estimated weights by mu*A*H and unscale the weights by
        # 10^-3 (note that Gmom was already rescaled (for improve scaling
        # for lsq inversion) as Gmom = Gmom*10^-3)

        # An effective depth for off-fault moment sources is required for scaling
        # This ought to be the averge depth over which off-fault sources contributed to surface strain
        # Total off-fault moment scales with this depth.
        # H = depth of off-fault moment  (meters)
        H = 15000; 
        # Off-fault moment calculation (distributed moments)
        # Conversion of weights (mhat_mom) to moments in N*m
        conv = 1e-3*mu*H*self.mesh["tri_areas"]*1e6 # tri_ares in km^2, convert to m^2, conversion factor (see notes above)

        if self.include_moment:
            m11 = self.mhat_mom[: len(self.mhat_mom) // 3] * conv  # dipole, force couple
            m12_m21 = (
                self.mhat_mom[len(self.mhat_mom) // 3 : 2 * len(self.mhat_mom) // 3] * conv
            )  # double couple m12 + m21
            m22 = (
                self.mhat_mom[2 * len(self.mhat_mom) // 3 :] * conv
            )  # dipole, force couple

            # Compute deviatoric moment tensor to get moment (Mo) of double-couple representations
            Mo = []
            for j in range(len(m11)):
                E = np.array(
                    [
                        [m11[j] - (m11[j] + m22[j]) / 2, 0.5 * m12_m21[j]],
                        [0.5 * m12_m21[j], m22[j] - (m11[j] + m22[j]) / 2],
                    ]
                )
                val, _ = np.linalg.eig(E)
                Mo.append(abs(val[0]))

            self.Mo_off = np.sum(Mo) 
        else:
            print('Moment rate explicitly not calculated. Defaulting to zero.')
            self.Mo_off = 0

        # Print moments
