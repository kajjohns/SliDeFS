"""
    get_observation_coords is specific to the formatting in this provided strain_rate_observation file.
    It assumes input coordinates are in lon/lat (wgs84) and that the params.cfg file contains information
    about the scale of the observation data. 

    It also assumes that strain rate data is formatted as Exx, Exy, Eyy.

    Feeding in lon0 and lat0 rather than using global constants from params.cfg because
    I'm testing two different geometries using csaf = True in main.ipynb
"""
def get_observation_coords(file, mesh, lon0, lat0):
    # get strain rate units
    scale = 1e-6 if data_params.getboolean("is_microstrain") else 1

    data = np.loadtxt(file, delimiter=",")

    # reindex data
    lon, lat = data[:, 0:2].T

    # convert observation data to local coordinates, crop to mesh limits
    x, y, z = geod_transform.geod2enu(lat, lon, 0, lat0, lon0, 0)

    # convert to km
    xyz = np.vstack((x, y, z)).T / 1000

    within_bounds = (
        (xyz[:, 0] > mesh["tri_centroids"][:, 0].min())
        & (xyz[:, 0] < mesh["tri_centroids"][:, 0].max())
        & (xyz[:, 1] > mesh["tri_centroids"][:, 1].min())
        & (xyz[:, 1] < mesh["tri_centroids"][:, 1].max())
    )
    xy_obs = xyz[within_bounds]
    E_means = data[within_bounds, 2:5] * scale
    E_stds = data[within_bounds, 5:8] * scale

    return xy_obs, E_means, E_stds


"""
    This function generates the Okada input geometry for a fault patch 
    defined by its 2D trace (x1, y1 and x2, y2), 
    total depth (not down-dip, but z value), and its dip (degrees).
"""


def get_pm(x1, y1, x2, y2, H, dip):
    xc, yc = (x1 + x2) / 2, (y1 + y2) / 2
    dx, dy = (x2 - x1), (y2 - y1)

    length = sqrt((dx) ** 2 + (dy) ** 2)
    angle = atan2(dy, dx)

    width = H / sin(radians(dip))

    # center of fault x+y is only the center at the surface if dip = 90
    # temp can be thought of as the horizontal distance from the epicenter to the fault surface trace
    # for an earthquake occurring at the center of the fault
    temp = abs(width) * cos(radians(dip))
    xo, yo = (-temp * cos(pi / 2 + angle), -temp * sin(pi / 2 + angle))

    strike = 90 - degrees(angle)
    return np.array((length, width, float(H), dip, strike, xc + xo, yc + yo))

"""
    This function performs piecewise smoothing for segments along a fault.
    Inputs are: 
        -fault object (used for getting number of segments)
        -A1 Greens functions for uniform slip
        -A2 Greens functions for tapered slip
        -for a 5 patch long fault, these correspond to:
           _ _ _ _ _
       A1:             <- uniform slip 
       A2: / / / / /   <- tapered slip (see below)
           0 1 2 3 4
        - where A2 is generated by discretizing the patch into n smaller segments, 
          and weighing each set of GFs more, beginning at 0 and ending at 1. 
        - for 4 smaller segments, each line here is 0.25 * unit slip

          0 1 2 3
                /|
              /  |
            /    |
          /      |
          0 1 2 3
        
    Output:
        -A creates a linear combination of A1 and A2 based on the length of the fault
        -modifies applied slip to taper at edges, e.g.
          _  
        /   \
        0 1 2 
"""


def piecewise_smoothing(n, A1, A2):
    A = np.zeros_like(A1)

    if n == 1:
        A[:, 0] = A1[:, 0]

    else:
        # First patch
        A[:, 0] = A1[:, 0] - A2[:, 0]

        # if 2 patches, python will skip this loop
        for j in range(1, n - 1):
            A[:, j] = A2[:, j - 1] + A1[:, j] - A2[:, j]

        # Last patch
        A[:, n - 1] = A2[:, n - 2] + A1[:, n - 1]

    return A


"""
    This function takes a single fault patch m, defined using the
    Okada geometry, and refines it into nhe horizontal and nve vertical 
    patches, returning them in a list of length nve*nhe 

    input: (7,) numpy array
    output: list contains nhe*nve (7,) numpy arrays
"""


def patchfault(m, nhe, nve):
    # if nhe == 1 & nve == 1:
    #    return([m])
    dip = radians(m[3])
    strike = -radians(m[4])
    sin_dip = sin(dip)
    cos_dip = cos(dip)
    iw = m[0] / nhe
    jw = m[1] / nve
    is_ = np.arange(1, nhe + 1)
    js = np.arange(1, nve + 1)

    n = nhe * nve
    c1 = -m[1] * cos_dip
    c2 = 0.5 * (m[0] + iw)
    c3 = m[2] - nve * jw * sin_dip

    # Calculate midpoints, depths of each patch
    p = np.outer(cos_dip * (jw * js - m[1]), np.ones(nhe))
    q = np.outer(np.ones(nve), (iw * is_) - 0.5 * (m[0] + iw))
    r = np.outer(m[2] - jw * sin_dip * (nve - js), np.ones(nhe))
    mp = np.column_stack((p.flatten(), q.flatten(), r.flatten()))

    # Adjust midpoints for strike
    R = np.array(
        [[cos(strike), -sin(strike), 0], [sin(strike), cos(strike), 0], [0, 0, 1]]
    )
    mp = np.dot(mp, R.T)

    # Adjust midpoints for offset from origin
    mp[:, 0] += m[5]
    mp[:, 1] += m[6]

    patch_models = []

    # Loop through and construct each patch model as a NumPy array
    for i in range(n):
        pm = np.zeros(7)
        pm[0] = iw
        pm[1] = jw
        pm[2] = mp[i, 2]
        pm[3:5] = m[3:5]  # Broadcasting for same values
        pm[5:7] = mp[i, 0:2]
        patch_models.append(pm)

    return patch_models


# Function to interpolate and handle NaN values for all columns at once
def interpolate_all(initial_coords, data, final_coords):
    # Interpolate all columns at once
    interp_data = griddata(
        initial_coords[:, :2], data, final_coords[:, :2], method="linear"
    )

    nan_mask = np.isnan(interp_data)
    if np.any(nan_mask):
        nearest_data = griddata(
            initial_coords[:, :2], data, final_coords[:, :2], method="nearest"
        )
        interp_data[nan_mask] = nearest_data[nan_mask]

    return interp_data


"""
    this function takes in an n by 4 array of segments for a single fault
    and a desired length for each segment
    it will upsample segments to match desired patch length (pL)
    without modifing ends of each segment, thus preserving input traces
    each row: [x1,y1,x2,y2] 
"""


def normalize_fault_segs(many_segs, pL):
    many_segs = np.atleast_2d(many_segs)
    new_segs = []
    index_vector = []

    for idx, (x1, y1, x2, y2) in enumerate(many_segs):
        dist = np.linalg.norm([x2 - x1, y2 - y1])
        nhe = int(np.ceil(dist / pL))  # Number of segments to split into
        xy_interp = np.linspace([x1, y1], [x2, y2], nhe + 1)

        # Create the sub-segments for this segment
        segs = np.column_stack((xy_interp[:-1], xy_interp[1:]))
        new_segs.append(segs)

        # Append the corresponding index for each new segment
        index_vector.extend([idx] * len(segs))

    return np.concatenate(new_segs, axis=0)

class Segment:
    # initialize default parameters as (effectively) a 2D strike slip model
    def __init__(self, segends, parent_fault):
        self.dip = parent_fault.dip
        self.rake = parent_fault.rake
        self.slip = parent_fault.slip
        self.h = parent_fault.h
        # initialize empty arrays for
        self.displacements = []
        self.gradients = []
        self.stresses = []
        self.fine_patches = []
        self.nhe = []
        self.nve = []
        self.parent_fault = parent_fault

        segends = np.array(segends)
        self.geometry = segends.reshape(2, 2)  # pm geometry (segment end points)
        (x1, y1), (x2, y2) = self.geometry
        self.pm = get_pm(x1, y1, x2, y2, self.h, self.dip)
        self.length = self.pm[0]

    def refine_patches(self, refine_length=1e6, nve=1):
        # Generate refined patches from geometry
        self.nhe = np.ceil(self.pm[0] / refine_length).astype(int)
        self.nve = nve

        self.fine_patches = (
            patchfault(self.pm, self.nhe, self.nve)
            if self.nhe > 1 or self.nve > 1
            else [self.pm]
        )

    # uses rake information to get slip vector for dislocation modeling
    # by default assumes unit slip. also assumes zero opening.
    def get_slip(self, perp=False, mag = 1):
        rake = self.rake + 90 if perp else self.rake
        strike_slip, dip_slip = cos(radians(rake)), sin(radians(rake))

        # if less than 1e-6, set to zero
        strike_slip = np.round(strike_slip, 6)
        dip_slip = np.round(dip_slip, 6)

        return [strike_slip * mag, dip_slip * mag, 0 * mag]

    def compute_disloc(self, slip, obs_xy):
        if not self.fine_patches:
            self.refine_patches()

        displacements, gradients, stresses = [], [], []
        for pf in self.fine_patches:

            new_pf = pf.copy()
            # convert to m from km
            new_pf[0:3] = new_pf[0:3] * 1000
            new_pf[5:7] = new_pf[5:7] * 1000
            # problem specific modification
            new_pf[2] += 1e-3
            
            u, g, s = dc3d_wrapper(new_pf, slip, obs_xy * 1000)
            displacements.append(u)
            gradients.append(g)
            stresses.append(s)

        self.displacements = np.array(displacements)
        self.gradients = np.array(gradients)
        self.stresses = np.array(stresses)

    def reshape(self, value):
        return np.array(value).reshape(self.nve, self.nhe, -1)

    def get_strain(self):

        Exx = self.gradients[:, :, 0]
        Exy = 0.5 * (self.gradients[:, :, 1] + self.gradients[:, :, 3])
        Eyy = self.gradients[:, :, 4]
        Exx = self.reshape(Exx)
        Exy = self.reshape(Exy)
        Eyy = self.reshape(Eyy)

        self.Exx = Exx
        self.Exy = Exy
        self.Eyy = Eyy

        return Exx, Exy, Eyy

    def get_disp(self):

        Ue = self.displacements[:, :, 0]
        Un = self.displacements[:, :, 1]
        Uu = self.displacements[:, :, 2]
        self.Ue = self.reshape(Ue)
        self.Un = self.reshape(Un)
        self.Uu = self.reshape(Uu)

    def compute_visco_strain(self, slip, obs_coords, pm = None):

        if pm is None:
            pm = self.pm
        # viscoelastic portion...
        Exx_visc, Exy_visc, Eyy_visc = visc_tools.get_interseismic_strain_rates_cycles(
            pm,
            slip,
            obs_coords[:, 0],
            obs_coords[:, 1],
            self.parent_fault.t_rec,
            self.parent_fault.t_eq,
        )
        return Exx_visc, Exy_visc, Eyy_visc

    def __repr__(self):
        if len(self.displacements) > 0:
            modeled = "Yes"
        else:
            modeled = "No"
        return f"Has GFs: {modeled}, nve,nhe: ({self.nve}, {self.nhe}), Loc: ({self.pm[5]:.1f},{self.pm[6]:.1f})\n"


class Fault:
    def __init__(
        self,
        dip=90,
        rake=0,
        fault_name="None",
        fault_id=0,
        slip=0,
        ub_slip=0,
        lb_slip=0,
        std_slip=0,
        t_rec=0,
        t_eq=0,
        h=1,
    ):
        self.fault_name = fault_name
        self.fault_id = fault_id
        self.dip = dip
        self.rake = rake
        self.slip = slip
        self.ub_slip = ub_slip
        self.lb_slip = lb_slip
        self.std_slip = std_slip
        self.h = h
        self.segments = []

        # if recurrence time is infinite, set it based on slip rate and average coseismic slip
        # coseismic slip (m) * 1000 mm/m * 1/(slip rate (mm/yr)) [=] years
        if np.isinf(t_rec):
            self.t_rec = coseismic_slip * 1000 / self.slip
        else:
            self.t_rec = t_rec

        # if time since earthquake is infinite (e.g. no earthquakes on record)
        # default time since last earthqake as a fraction of recurrence time
        if np.isinf(t_eq):
            self.t_eq = t_eq_frac * self.t_rec
        else:
            self.t_eq = t_eq

    def __repr__(self):
        fault_info = f"Fault(Name: {self.fault_name}, ID: {self.fault_id}, Num Segs: {len(self.segments)}, Dip: {self.dip}, Rake: {self.rake}, Slip: {self.slip})"
        seg_info = "".join(
            [f"    Seg {i}: {segment}" for i, segment in enumerate(self.segments)]
        )  # Indentation added before each segment
        return f"{fault_info}\n{seg_info}"

    def add_segment(self, segends):
        # first we want to normalize the length of the segments
        # this is different from our fine patch refinement...
        segment = Segment(segends, self)
        self.segments.append(segment)
        return segment

    def compute_green_functions(self, piecewise=False):

        # below this is going to go into Fault class...
        E1xx, E1yy, E1xy = [], [], []
        E2xx, E2yy, E2xy = [], [], []

        # Loop through each segment (patch) in the fault
        for patch in self.segments:
            # Compute E1 by summing over all axes
            E1xx.append(patch.Exx.sum(axis=(0,1)))
            E1yy.append(patch.Eyy.sum(axis=(0,1)))
            E1xy.append(patch.Exy.sum(axis=(0,1)))

            if piecewise:
                if patch.nhe == 1:
                    print(
                        "warning: attempting to perform  piecewise smoothing with only one horizontal element."
                    )
                # Compute E2 using a single loop with tapering

                frac = np.arange(patch.nhe) / patch.nhe
                E2xx.append((patch.Exx * frac[:, None]).sum(axis=(0, 1)))
                E2yy.append((patch.Eyy * frac[:, None]).sum(axis=(0, 1)))
                E2xy.append((patch.Exy * frac[:, None]).sum(axis=(0, 1)))

        if piecewise:
            # Apply piecewise smoothing on computed displacements
            num = len(self.segments)
            self.GExx = piecewise_smoothing(num, np.array(E1xx).T, np.array(E2xx).T)
            self.GExy = piecewise_smoothing(num, np.array(E1xy).T, np.array(E2xy).T)
            self.GEyy = piecewise_smoothing(num, np.array(E1yy).T, np.array(E2yy).T)

            self.G1Exx = np.array(E1xx).T
            self.G1Exy = np.array(E1xy).T
            self.G1Eyy = np.array(E1yy).T

            self.G2Exx = np.array(E2xx).T
            self.G2Exy = np.array(E2xy).T
            self.G2Eyy = np.array(E2yy).T

        else:
            self.GExx = np.array(E1xx).T
            self.GEyy = np.array(E1yy).T
            self.GExy = np.array(E1xy).T

def make_fault_from_matlab(one_fault, height):

    def extract_scalar(value):
        while isinstance(value, np.ndarray) and value.size == 1:
            value = value.item() 
        return value

    result = {}
    for key in one_fault.dtype.fields.keys():
        value = extract_scalar(one_fault[key])

        if isinstance(value, np.ndarray) and value.size == 0:
            value = None

        result[key] = value

    f1 = Fault(
        dip=result["Dip"],
        rake=result["Rake"],
        fault_id=result["FaultID"],
        fault_name=result["FaultName"],
        slip=result["PrefSlipRate"],
        ub_slip=result["UBSlipRate"],
        lb_slip=result["LBSlipRate"],
        std_slip=result["STDSlipRate"],
        t_rec=result["RecurrenceTime"],
        t_eq=result["TimeSinceEq"],
        h=height,
    )

    return f1


